-- Run this script in the Supabase SQL Editor for the public.wishes table.
CREATE TABLE IF NOT EXISTS public.wishes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (char_length(trim(name)) BETWEEN 2 AND 100),
    attendance text NOT NULL CHECK (attendance IN ('Hadir', 'Tidak Hadir', 'Masih Ragu')),
    message text NOT NULL CHECK (char_length(trim(message)) BETWEEN 3 AND 1000),
    created_at timestamptz NOT NULL DEFAULT now(),
    is_visible boolean NOT NULL DEFAULT true
);

ALTER TABLE public.wishes
    ADD COLUMN IF NOT EXISTS is_visible boolean NOT NULL DEFAULT true;

CREATE INDEX IF NOT EXISTS wishes_created_at_idx ON public.wishes (created_at DESC);

ALTER TABLE public.wishes ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON public.wishes TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.wishes_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS "Anyone can read visible wishes" ON public.wishes;
CREATE POLICY "Anyone can read visible wishes"
    ON public.wishes FOR SELECT
    TO anon, authenticated
    USING (is_visible IS TRUE);

DROP POLICY IF EXISTS "Anyone can send wishes" ON public.wishes;
CREATE POLICY "Anyone can send wishes"
    ON public.wishes FOR INSERT
    TO anon, authenticated
    WITH CHECK (
        char_length(trim(name)) BETWEEN 2 AND 100
        AND attendance IN ('Hadir', 'Tidak Hadir', 'Masih Ragu')
        AND char_length(trim(message)) BETWEEN 3 AND 1000
        AND is_visible IS TRUE
    );

DROP POLICY IF EXISTS "RSVP deadline" ON public.wishes;
CREATE POLICY "RSVP deadline"
    ON public.wishes AS RESTRICTIVE
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (now() < TIMESTAMPTZ '2027-03-21 08:00:00+07:00');
